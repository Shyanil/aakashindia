#!/usr/bin/env node
// Converts the images the homepage actually references into optimized WebP files.
//
//   assets/aakash-india-originals/<name>.<jpg|png|...>   (downloaded, not served)
//     -> public/images/aakash-india/<name>.webp          (served, used by next/image)
//
// References are found by scanning app/, components/ and lib/ for local image names
// ("<yyyy>-<mm>-<name>.<ext>", as written by download-images.mjs), matched to originals
// by name regardless of extension, so the script can be re-run after content changes. Also writes app/icon.png and
// app/apple-icon.png from the original site icon.
//
// Usage: node scripts/optimize-images.mjs

import { readdir, readFile, writeFile, mkdir, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.join(root, "assets/aakash-india-originals");
const outDir = path.join(root, "public/images/aakash-india");

const MAX_WIDTH = 2400; // largest rendition next/image will ever request from us
const PHOTO = { quality: 78, effort: 6, smartSubsample: true };
const GRAPHIC = { quality: 90, alphaQuality: 100, effort: 6 }; // logos / transparent art

const stripExt = (f) => f.replace(/(\.(jpe?g|png|webp))+$/i, "");

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (/\.(tsx?|css)$/.test(e.name)) out.push(p);
  }
  return out;
}

const sources = (await Promise.all(["app", "components", "lib"].map((d) => walk(path.join(root, d))))).flat();
const referenced = new Set();
for (const f of sources) {
  const text = await readFile(f, "utf8");
  for (const m of text.matchAll(/(?<=[/"'`])(\d{4}-\d{2}-[a-z0-9_.-]+?)(?:\.(?:jpe?g|png|webp))+(?![a-z0-9_.-])/gi)) {
    referenced.add(m[1]);
  }
}

const originals = new Map(
  (await readdir(srcDir)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).map((f) => [stripExt(f), f]),
);

await mkdir(outDir, { recursive: true });
let before = 0, after = 0;
const missing = [];
for (const name of [...referenced].sort()) {
  const file = originals.get(name);
  if (!file) {
    missing.push(name);
    continue;
  }
  const input = path.join(srcDir, file);
  const meta = await sharp(input).metadata();
  const isGraphic = meta.hasAlpha; // transparent logos/art; PNG photos get photo settings
  const base = () => sharp(input).rotate().resize({ width: MAX_WIDTH, withoutEnlargement: true });
  // Graphics: keep whichever of lossy / lossless WebP is smaller (line art often favours lossless).
  const candidates = isGraphic
    ? [base().webp(GRAPHIC), base().webp({ lossless: true, effort: 6 })]
    : [base().webp(PHOTO)];
  const outputs = await Promise.all(candidates.map((c) => c.toBuffer({ resolveWithObject: true })));
  const best = outputs.reduce((a, b) => (b.data.length < a.data.length ? b : a));
  const out = path.join(outDir, `${name}.webp`);
  await writeFile(out, best.data);
  const info = { ...best.info, size: best.data.length };
  const inSize = (await stat(input)).size;
  before += inSize;
  after += info.size;
  console.log(
    `${name}.webp  ${info.width}x${info.height}  ${Math.round(inSize / 1024)} KB -> ${Math.round(info.size / 1024)} KB`,
  );
}

// Favicons via Next's file conventions.
const icon = path.join(srcDir, "2023-12-cropped-348961407_1300267597588698_4887816145498378163_n-270x270.jpg");
await sharp(icon).resize(192).png().toFile(path.join(root, "app/icon.png"));
await sharp(icon).resize(180).png().toFile(path.join(root, "app/apple-icon.png"));

console.log(`\n${referenced.size - missing.length} images: ${Math.round(before / 1024)} KB -> ${Math.round(after / 1024)} KB`);
if (missing.length) {
  console.error(`No original found for: ${missing.join(", ")}`);
  process.exitCode = 1;
}
await writeFile(
  path.join(outDir, "README.txt"),
  "Generated by scripts/optimize-images.mjs from assets/aakash-india-originals/. Do not edit by hand.\n",
);
